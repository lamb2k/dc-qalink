#!/usr/bin/env python3
"""mkfont.py: the in-game menu's font (lib/dcql_menu.c) from Spleen 8x16's BDF. MIT licence (this script); the glyphs
are Spleen's (BSD 2-Clause, Frederic Cambus, see LICENSE-spleen.txt).

    python3 lib/font/mkfont.py spleen-8x16.bdf          # writes lib/font/spleen8x16.h and lib/font/RECEIPT.txt
    python3 lib/font/mkfont.py spleen-8x16.bdf --check  # exit 1 if the committed header or receipt does not match

Only the printable ASCII glyphs (32..126) are kept: 95 glyphs x 16 rows, one byte a row, bit 7 = the left pixel
(1,520 bytes). The source is Spleen 2.3.0 (https://github.com/fcambus/spleen, spleen-8x16.bdf); the receipt holds the
SHA-256 of the BDF, of this script and of the header it wrote.
"""
import hashlib, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIRST, LAST = 32, 126


def glyphs(bdf_text):
    out, enc, bits, bbx, inb = {}, -1, [], None, False
    fbb = None
    for line in bdf_text.splitlines():
        if line.startswith('FONTBOUNDINGBOX '):
            fbb = [int(v) for v in line.split()[1:]]
        elif line.startswith('ENCODING '):
            enc = int(line.split()[1])
        elif line.startswith('BBX '):
            bbx = [int(v) for v in line.split()[1:]]
        elif line == 'BITMAP':
            inb, bits = True, []
        elif line == 'ENDCHAR':
            inb = False
            if FIRST <= enc <= LAST:
                w, h, xo, yo = bbx
                # place the glyph's box in the 8x16 cell: the cell's bottom is the font's descent (fbb[3], -4)
                top = (16 + fbb[3]) - (yo + h)
                rows = [0] * 16
                for i, b in enumerate(bits):
                    y = top + i
                    v = int(b, 16) >> (len(b) * 4 - 8) if len(b) * 4 >= 8 else int(b, 16) << (8 - len(b) * 4)
                    if 0 <= y < 16:
                        rows[y] = (v >> xo) & 0xff
                out[enc] = rows
        elif inb:
            bits.append(line.strip())
    missing = [c for c in range(FIRST, LAST + 1) if c not in out]
    if missing:
        raise SystemExit('mkfont: glyphs missing from the BDF: %s' % missing)
    return out


def header(g, bdf_sha, script_sha):
    lines = ['/* spleen8x16.h: generated by lib/font/mkfont.py; do not edit. The in-game menu\'s font.',
             ' * Spleen 8x16 2.3.0, Copyright (c) 2018-2026, Frederic Cambus, BSD 2-Clause licence (LICENSE-spleen.txt',
             ' * beside this file; https://github.com/fcambus/spleen). Glyphs %d..%d only, 16 rows each, bit 7 = left pixel.' % (FIRST, LAST),
             ' * BDF sha256 %s' % bdf_sha,
             ' * mkfont.py sha256 %s */' % script_sha,
             '#define DCQL_FONT_FIRST %d' % FIRST, '#define DCQL_FONT_LAST %d' % LAST,
             'static const unsigned char dcql_font[%d][16] = {' % (LAST - FIRST + 1)]
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        note = '' if ch in '\\*/' else ' /* %s */' % ch
        lines.append('    {%s},%s' % (','.join('0x%02x' % v for v in g[c]), note))
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main():
    bdf = Path(sys.argv[1]).read_bytes()
    bdf_sha = hashlib.sha256(bdf).hexdigest()
    script_sha = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    text = header(glyphs(bdf.decode('latin1')), bdf_sha, script_sha)
    out_sha = hashlib.sha256(text.encode()).hexdigest()
    receipt = 'input spleen-8x16.bdf (Spleen 2.3.0) sha256 %s\nscript lib/font/mkfont.py sha256 %s\noutput lib/font/spleen8x16.h sha256 %s\n' % (
        bdf_sha, script_sha, out_sha)
    if '--check' in sys.argv:
        ok = (HERE / 'spleen8x16.h').read_text() == text and (HERE / 'RECEIPT.txt').read_text() == receipt
        print('mkfont check:', 'ok' if ok else 'MISMATCH')
        sys.exit(0 if ok else 1)
    (HERE / 'spleen8x16.h').write_text(text)
    (HERE / 'RECEIPT.txt').write_text(receipt)
    print('mkfont: %d glyphs, %d bytes; header sha256 %s' % (LAST - FIRST + 1, (LAST - FIRST + 1) * 16, out_sha))


if __name__ == '__main__':
    main()
